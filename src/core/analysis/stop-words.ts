/** Every stop word of every supported language, for constant-time lookup. */
const STOP_WORDS: ReadonlySet<string> = new Set([...ENGLISH_STOP_WORDS, ...SPANISH_STOP_WORDS]);

/**
 * Tells whether a word is a filler word that should not be counted.
 *
 * @param lowerCasedWord - A word already converted to lower case.
 * @returns `true` for English and Spanish stop words.
 */
export function isStopWord(lowerCasedWord: string): boolean {
  return STOP_WORDS.has(lowerCasedWord);
}
